#include <bits/stdc++.h>
#include <queue>

using namespace std;

int main() {
    using pii=pair<int,int>;
    int N;cin>>N;
    priority_queue<pii> s;
    priority_queue<int> pq;
    for (int i=1;i<=N;i++){
        int E,H;cin>>E>>H;
        s.push({E,H});
    }
    long long ans=0;
    for (int i=200000;i>=1;i--){
        while (!s.empty()&&s.top().first>=i) {
            pq.push(s.top().second);
            s.pop();
        }
        if (!pq.empty()) {
            ans+=pq.top();
            pq.pop();
        }
    }
    cout<<ans<<endl;
}

